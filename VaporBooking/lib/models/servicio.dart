class Servicio {
  final int id;
  final String nombre;
  final String descripcion;
  final int precio;
  final int duracion;
  final int valoracionPuntos;

  const Servicio({
    required this.id,
    required this.nombre,
    required this.descripcion,
    required this.precio,
    required this.duracion,
    required this.valoracionPuntos,
  });
}
